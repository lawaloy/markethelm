"""Hosted dual-channel PUTs must keep email when webhook is dropped.

Dropping webhook from a watch that also has email (#458 is webhook-only→log;
#463 is email-drop keeping webhook) must still SendGrid the tenant mailbox and
must not POST the stored webhook URL. A sibling tenant must still notify its
own URL. Process-wide ``ALERT_EMAIL_TO`` / ``ALERT_WEBHOOK_URL`` must not leak
into hosted sends.
"""

